// SEC-02: Cloudflare static-asset security and cache headers
Deno.test('SEC-02: web/_headers declares global security headers and cache policies', () => {
  const content = Deno.readTextFileSync(new URL('../web/_headers', import.meta.url));

  // Security headers under /*
  assert(content.includes('/*'), 'contains /* section');
  assert(content.includes('X-Content-Type-Options: nosniff'), 'X-Content-Type-Options');
  assert(content.includes('X-Frame-Options: DENY'), 'X-Frame-Options');
  assert(content.includes('Referrer-Policy: strict-origin-when-cross-origin'), 'Referrer-Policy');
  assert(content.includes('Permissions-Policy: accelerometer=(), camera=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), payment=(), usb=()'), 'Permissions-Policy');
  assert(content.includes("Content-Security-Policy: default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; worker-src 'self' blob:; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'"), 'Content-Security-Policy');

  // Application cache rules
  assert(content.includes('/index.html\n  Cache-Control: no-cache, no-store, must-revalidate'), 'index.html cache policy');
  assert(content.includes('/*.js\n  Cache-Control: public, max-age=0, must-revalidate'), 'js cache policy');
  assert(content.includes('/*.css\n  Cache-Control: public, max-age=0, must-revalidate'), 'css cache policy');

  // Vendor immutability rules
  assert(content.includes('/vendor/occt-import-js-0.0.23/*\n  Cache-Control: public, max-age=31536000, immutable'), 'occt cache policy');
  assert(content.includes('/vendor/three/*\n  Cache-Control: public, max-age=31536000, immutable'), 'three cache policy');
});

